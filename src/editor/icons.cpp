ImU32 Shaded(ImU32 colour) {
    ImU32 alpha = ImU32(float(colour >> IM_COL32_A_SHIFT & 0xFF) * kShade);
    return (colour & ~IM_COL32_A_MASK) | (alpha << IM_COL32_A_SHIFT);
}

