void DrawIcon(ImDrawList* draw, Icon icon, ImVec2 min, float size, ImU32 colour) {
    // whole screen pixels per art pixel keeps edges sharp
    float scale = std::fmax(1.0f, std::round(size / kPixels));
    float x0 = std::floor(min.x + (size - scale * kPixels) * 0.5f);
    float y0 = std::floor(min.y + (size - scale * kPixels) * 0.5f);
    ImU32 shade = Shaded(colour);
    for (int y = 0; y < kPixels; y++) {
        for (int x = 0; x < kPixels; x++) {
            char c = kArt[int(icon)][y][x];
            if (c == '.') continue;
            ImVec2 at(x0 + x * scale, y0 + y * scale);
            draw->AddRectFilled(at, ImVec2(at.x + scale, at.y + scale), c == '#' ? colour : shade);
        }
    }
}

